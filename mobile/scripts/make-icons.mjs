// App icons for iOS and Android, same artwork as the desktop and PWA icons (web/scripts/make-pwa-icons.mjs): three white
// bars on green. iOS wants one opaque 1024 px square (the system rounds it); Android gets an adaptive icon as vectors.
// Run: node mobile/scripts/make-icons.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { deflateSync } from 'node:zlib';

const bg = [0, 168, 45];
const fg = [255, 255, 255];
// Bars in a 1024 square: centre x, centre y, half width, half height; corner radius 24.
const BARS = [[512, 328, 205, 41], [512, 512, 205, 41], [410, 696, 103, 41]];

const rrDist = (x, y, cx, cy, hw, hh, r) => {
  const qx = Math.abs(x - cx) - (hw - r);
  const qy = Math.abs(y - cy) - (hh - r);
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r;
};
const cover = (d) => Math.min(1, Math.max(0, 0.5 - d));

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
};

/** Opaque RGB square, bars scaled by [s] around the centre (no alpha: App Store icons must not have any). */
function png(N, s) {
  const k = N / 1024;
  const bars = BARS.map(([cx, cy, hw, hh]) => [(512 + (cx - 512) * s) * k, (512 + (cy - 512) * s) * k, hw * s * k, hh * s * k]);
  const raw = Buffer.alloc(N * (N * 3 + 1));
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; x++) {
      let t = 0;
      for (const [cx, cy, hw, hh] of bars) t = Math.max(t, cover(rrDist(x + 0.5, y + 0.5, cx, cy, hw, hh, 24 * s * k)));
      const o = y * (N * 3 + 1) + 1 + x * 3;
      for (let c = 0; c < 3; c++) raw[o + c] = Math.round(bg[c] * (1 - t) + fg[c] * t);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(N, 0);
  ihdr.writeUInt32BE(N, 4);
  ihdr.set([8, 2, 0, 0, 0], 8);
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}

/** Rounded rectangles as vector path data, mapped from the 1024 square into [size] with the art [scale]d. */
function vectorBars(size, scale) {
  const f = (v) => +(v.toFixed(2));
  return BARS.map(([cx, cy, hw, hh]) => {
    const m = (v) => size / 2 + ((v - 512) * scale * size) / 1024;
    const x0 = m(cx - hw), x1 = m(cx + hw), y0 = m(cy - hh), y1 = m(cy + hh), r = (24 * scale * size) / 1024;
    return `M${f(x0 + r)},${f(y0)}H${f(x1 - r)}A${f(r)},${f(r)} 0,0 1,${f(x1)},${f(y0 + r)}V${f(y1 - r)}A${f(r)},${f(r)} 0,0 1,${f(x1 - r)},${f(y1)}` +
      `H${f(x0 + r)}A${f(r)},${f(r)} 0,0 1,${f(x0)},${f(y1 - r)}V${f(y0 + r)}A${f(r)},${f(r)} 0,0 1,${f(x0 + r)},${f(y0)}Z`;
  }).join('');
}

const root = new URL('../', import.meta.url);
const write = (rel, data) => {
  const url = new URL(rel, root);
  mkdirSync(new URL('./', url), { recursive: true });
  writeFileSync(url, data);
  console.log('wrote mobile/' + rel);
};

// iOS: the same proportions as the PWA's apple-touch-icon (art at 80%).
const appIcon = 'iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/';
write(appIcon + 'icon-1024.png', png(1024, 0.8));
write(appIcon + 'Contents.json', JSON.stringify({
  images: [{ filename: 'icon-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' }],
  info: { author: 'xcode', version: 1 },
}, null, 2) + '\n');
write('iosApp/iosApp/Assets.xcassets/Contents.json', JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');

// Android adaptive icon: 108 dp layers, of which the launcher shows the middle 72 (and may cut it to a circle of 66).
const res = 'androidApp/src/main/res/';
const hex = '#' + bg.map((c) => c.toString(16).padStart(2, '0')).join('').toUpperCase();
write(res + 'values/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${hex}</color>\n</resources>\n`);
write(res + 'drawable/ic_launcher_foreground.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/make-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFFFF" android:pathData="${vectorBars(108, 0.6)}" />
</vector>
`);
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`;
write(res + 'mipmap-anydpi-v26/ic_launcher.xml', adaptive);
