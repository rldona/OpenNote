// The app's UI, shared by Android and iOS (Compose Multiplatform). The note body is the web editor in a WebView
// (web/src/embed), everything around it is native.
plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.compose.multiplatform)
    alias(libs.plugins.android.kmp.library)
}

// Google OAuth clients for Drive sync (docs/GOOGLE-DRIVE-SETUP.md), given to the build like the desktop's: a Gradle property
// or an environment variable (CI variables). Client IDs are public; mobile clients have no secret. Empty: no Drive sync.
fun googleClient(name: String) = providers.gradleProperty("opennote.google${name}ClientId")
    .orElse(providers.environmentVariable("OPENNOTE_GOOGLE_${name.uppercase()}_CLIENT_ID")).orElse("")
val googleIos = googleClient("Ios")
val googleAndroid = googleClient("Android")
val generateGoogleClients = tasks.register("generateGoogleClients") {
    val out = layout.buildDirectory.dir("generated/googleClients")
    inputs.property("ios", googleIos)
    inputs.property("android", googleAndroid)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("app/opennote/ui").apply { mkdirs() }
        dir.resolve("GoogleClients.kt").writeText(
            "// Generated by composeApp/build.gradle.kts (generateGoogleClients). Do not edit.\n" +
                "package app.opennote.ui\n\n" +
                "internal const val GOOGLE_IOS_CLIENT_ID = \"${googleIos.get().trim()}\"\n" +
                "internal const val GOOGLE_ANDROID_CLIENT_ID = \"${googleAndroid.get().trim()}\"\n",
        )
    }
}

